use rayon::prelude::*;

use std::path::{Path, PathBuf};

// Keep synchronized with `skip_crate_headers` in src/libmongoac/CMakeLists.txt.
const SKIP_CRATE_HEADERS: &[&str] = &["lib", "mod", "version"];

// Keep synchronized with `skip_forward_headers` in src/libmongoac/CMakeLists.txt.
const SKIP_FORWARD_HEADERS: &[&str] = &["bson", "string"];

// Prelude shared by all generated headers.
fn generate_header() -> String {
    [
        "// Copyright 2009-present MongoDB, Inc.",
        "//",
        "// Licensed under the Apache License, Version 2.0 (the \"License\");",
        "// you may not use this file except in compliance with the License.",
        "// You may obtain a copy of the License at",
        "//",
        "// http://www.apache.org/licenses/LICENSE-2.0",
        "//",
        "// Unless required by applicable law or agreed to in writing, software",
        "// distributed under the License is distributed on an \"AS IS\" BASIS,",
        "// WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.",
        "// See the License for the specific language governing permissions and",
        "// limitations under the License.",
        "",
        "// Generated by src/libmongoac/tools/generate-crate-headers/src/main.rs.",
    ]
    .join("\n")
}

// Rename structs from `ExampleT` to `mongoac_example_t`.
fn rename_structs() -> std::collections::HashMap<String, String> {
    let pairs: &[(&str, &str)] = &[
        ("BsonT", "mongoac_bson_t"),
        ("BsonViewT", "mongoac_bson_view_t"),
        ("ClientSessionT", "mongoac_client_session_t"),
        ("ClientT", "mongoac_client_t"),
        ("CollectionOptionsT", "mongoac_collection_options_t"),
        ("CollectionT", "mongoac_collection_t"),
        ("CountOptionsT", "mongoac_count_options_t"),
        ("DatabaseOptionsT", "mongoac_database_options_t"),
        ("DatabaseT", "mongoac_database_t"),
        (
            "DropCollectionOptionsT",
            "mongoac_drop_collection_options_t",
        ),
        ("DropDatabaseOptionsT", "mongoac_drop_database_options_t"),
        ("ErrorT", "mongoac_error_t"),
        (
            "EstimatedDocumentCountOptionsT",
            "mongoac_estimated_document_count_options_t",
        ),
        ("FutureT", "mongoac_future_t"),
        ("InsertManyOptionsT", "mongoac_insert_many_options_t"),
        ("InsertManyResultT", "mongoac_insert_many_result_t"),
        ("InsertOneOptionsT", "mongoac_insert_one_options_t"),
        ("InsertOneResultT", "mongoac_insert_one_result_t"),
        ("RunCommandOptionsT", "mongoac_run_command_options_t"),
        ("RuntimeT", "mongoac_runtime_t"),
        ("StringT", "mongoac_string_t"),
        ("StringViewT", "mongoac_string_view_t"),
    ];

    pairs
        .iter()
        .map(|(k, v)| (k.to_string(), v.to_string()))
        .collect()
}

// Module-specific configuration options.
fn configure(name: &str, config: &mut cbindgen::Config) {
    // Include directives required by each crate header.
    {
        #[allow(clippy::match_same_arms)]
        let headers: &[&str] = match name {
            "bson" => &["stdint.h"],
            "client_session" => &[],
            "collection_options" => &[],
            "collection" => &[
                "mongoac/bson.h",
                "mongoac/client_session-fwd.h",
                "mongoac/client-fwd.h",
                "mongoac/count_options-fwd.h",
                "mongoac/drop_collection_options-fwd.h",
                "mongoac/error-fwd.h",
                "mongoac/estimated_document_count_options-fwd.h",
                "mongoac/future-fwd.h",
                "mongoac/insert_many_options-fwd.h",
                "mongoac/insert_one_options-fwd.h",
                "mongoac/insert_one_result-fwd.h",
                "mongoac/runtime-fwd.h",
                "mongoac/string.h",
                "stdint.h",
            ],
            "count_options" => &[],
            "client" => &[
                "mongoac/database_options-fwd.h",
                "mongoac/database-fwd.h",
                "mongoac/error-fwd.h",
                "mongoac/future-fwd.h",
                "mongoac/runtime-fwd.h",
                "mongoac/string.h",
                "stdint.h",
            ],
            "database_options" => &[],
            "database" => &[
                "mongoac/bson.h",
                "mongoac/client_session-fwd.h",
                "mongoac/client-fwd.h",
                "mongoac/collection_options-fwd.h",
                "mongoac/collection-fwd.h",
                "mongoac/drop_database_options-fwd.h",
                "mongoac/error-fwd.h",
                "mongoac/future-fwd.h",
                "mongoac/run_command_options-fwd.h",
                "mongoac/runtime-fwd.h",
                "mongoac/string.h",
                "stdint.h",
            ],
            "drop_collection_options" => &[],
            "drop_database_options" => &[],
            "estimated_document_count_options" => &[],
            "error" => &["mongoac/string.h", "stdint.h"],
            "future" => &[
                "mongoac/bson.h",
                "mongoac/error-fwd.h",
                "mongoac/insert_many_result-fwd.h",
                "mongoac/insert_one_result-fwd.h",
                "mongoac/runtime-fwd.h",
                "stdbool.h",
                "stdint.h",
            ],
            "insert_many_options" => &[],
            "insert_many_result" => &["mongoac/bson.h", "mongoac/error-fwd.h"],
            "insert_one_options" => &[],
            "insert_one_result" => &["mongoac/bson.h", "mongoac/error-fwd.h"],
            "run_command_options" => &[],
            "runtime" => &["mongoac/future-fwd.h", "mongoac/error-fwd.h", "stdint.h"],
            "string" => &["stdint.h"],
            _ => {
                eprintln!("warning: missing generate-crate-headers entry: {name}");
                &[]
            }
        };

        config
            .sys_includes
            .extend(headers.iter().map(ToString::to_string));
    }

    // Structs which need to be explicitly exported (due to no exported function referencing the struct).
    {
        let exports: &[&str] = match name {
            "bson" => &["BsonViewT"],
            "string" => &["StringViewT"],
            _ => &[],
        };

        config
            .export
            .include
            .extend(exports.iter().map(ToString::to_string));
    }
}

fn default_config() -> cbindgen::Config {
    cbindgen::Config {
        language: cbindgen::Language::C,
        style: cbindgen::Style::Both,
        header: Some(generate_header()),
        cpp_compat: true,
        braces: cbindgen::Braces::NextLine,
        line_length: 120,
        tab_width: 3,
        documentation: false,
        documentation_style: cbindgen::DocumentationStyle::C99,
        export: cbindgen::ExportConfig {
            rename: rename_structs(),
            ..Default::default()
        },
        function: cbindgen::FunctionConfig {
            prefix: Some("MONGOAC_ABI_EXPORT".to_owned()),
            ..Default::default()
        },
        no_includes: true,
        ..Default::default()
    }
}

fn generate_forward_header(mod_path: &Path, rel_stem: &Path, include_dir: &Path) {
    let rel_str = rel_stem.to_str().expect("invalid UTF-8");

    // `path/to/module` -> `MONGOAC_PATH_TO_MODULE_FWD_H`
    let include_guard = format!(
        "MONGOAC_{}_FWD_H",
        rel_str
            .replace(std::path::MAIN_SEPARATOR, "_")
            .to_uppercase()
    );

    // `path/to/module` -> `<include_dir>/path/to/module-fwd.h`
    // Parent directories are already created by `generate_crate_header()`.
    let header_path = include_dir.join(rel_stem).with_file_name(format!(
        "{}-fwd.h",
        rel_stem
            .file_name()
            .and_then(|s| s.to_str())
            .expect("invalid UTF-8")
    ));

    let config = {
        let mut config = default_config();

        // Only forward declarations of opaque structs.
        config.export.item_types = vec![cbindgen::ItemType::OpaqueItems];

        config
    };

    // Generate the forward header.
    cbindgen::Builder::new()
        .with_config(config)
        .with_include_guard(&include_guard)
        .with_src(mod_path)
        .generate()
        .expect("cbindgen failed")
        .write_to_file(&header_path);
}

fn add_fwd_iwyu_pragma(header_path: &Path, directive: &str) {
    const IWYU_PRAGMA_EXPORT: &str = " // IWYU pragma: export";

    let mut content = std::fs::read_to_string(header_path)
        .unwrap_or_else(|_| panic!("failed to read header: {}", header_path.display()));

    let expected = format!("{directive}{IWYU_PRAGMA_EXPORT}");

    // Starting position of `#include <mongoac/example-fwd.h>`.
    let index = content.find(directive).unwrap_or_else(|| {
        // This function should be guarded by `SKIP_FORWARD_HEADERS`.
        panic!(
            "include directive for forward header missing in {}: {directive}",
            header_path.display()
        )
    });

    // IWYU pragma is already present.
    if content[index..].starts_with(&expected) {
        return; // Nothing to do.
    }

    // Substitute patched include directive.
    content.replace_range(index..index + directive.len(), &expected);
    std::fs::write(header_path, content)
        .unwrap_or_else(|_| panic!("failed to write header: {}", header_path.display()));
}

fn generate_crate_header(mod_path: &Path, src_dir: &Path, include_dir: &Path) {
    let file_stem = mod_path
        .file_stem()
        .and_then(|s| s.to_str())
        .expect("invalid UTF-8");

    // `src/libmongoac/src/path/to/module.rs` -> `path/to/module`
    let rel_path = mod_path
        .strip_prefix(src_dir)
        .expect("file not under src root");
    let rel_stem = rel_path.with_extension("");
    let rel_str = rel_stem.to_str().expect("invalid UTF-8");

    // `path/to/module` -> `MONGOAC_PATH_TO_MODULE_H`
    let include_guard = format!(
        "MONGOAC_{}_H",
        rel_str
            .replace(std::path::MAIN_SEPARATOR, "_")
            .to_uppercase()
    );

    // `path/to/module` -> `<include_dir>/path/to/module.h`
    let header_path = include_dir.join(&rel_stem).with_extension("h");
    if let Some(parent) = header_path.parent() {
        std::fs::create_dir_all(parent)
            .unwrap_or_else(|_| panic!("failed to create include directory: {}", parent.display()));
    }

    // Default cbindgen configuration for all modules.
    let config = {
        let mut config = default_config();

        // All except `OpaqueItems` (which is declared in the forward header).
        config.export.item_types = vec![
            cbindgen::ItemType::Functions,
            cbindgen::ItemType::Typedefs,
            cbindgen::ItemType::Constants,
            cbindgen::ItemType::Enums,
            cbindgen::ItemType::Structs,
            cbindgen::ItemType::Unions,
        ];

        // Always include the component's forward header first.
        if !SKIP_FORWARD_HEADERS.contains(&file_stem) {
            generate_forward_header(mod_path, &rel_stem, include_dir);
            config.sys_includes.push(format!("mongoac/{rel_str}-fwd.h"));
        }

        // Normal headers typically export at least one symbol.
        config.sys_includes.push("mongoac/export.h".into());

        // Apply per-module configuration options.
        configure(rel_str, &mut config);

        config
    };

    // Generate the crate header.
    cbindgen::Builder::new()
        .with_config(config)
        .with_include_guard(&include_guard)
        .with_src(mod_path)
        .generate()
        .expect("cbindgen failed")
        .write_to_file(&header_path);

    // Patch the header's include directive of its forward header with `// IWYU pragma: export`.
    if !SKIP_FORWARD_HEADERS.contains(&file_stem) {
        let directive = format!("#include <mongoac/{rel_str}-fwd.h>");
        add_fwd_iwyu_pragma(&header_path, &directive);
    }
}

// Recursively find all mongoac modules under the source directory which need a header.
fn find_modules(dir: &Path, files: &mut Vec<PathBuf>) {
    for entry in std::fs::read_dir(dir)
        .unwrap_or_else(|_| panic!("failed to read directory: {}", dir.display()))
    {
        let path = entry.map_or_else(
            |_| panic!("failed to read directory entry: {}", dir.display()),
            |e| e.path(),
        );

        if path.is_dir() {
            if path.file_name().is_some_and(|name| name == "private") {
                continue; // Private modules do not need headers.
            }

            find_modules(&path, files);
        } else if path.extension().is_some_and(|e| e == "rs") {
            let file_stem = path
                .file_stem()
                .and_then(|s| s.to_str())
                .expect("invalid UTF-8");

            if !SKIP_CRATE_HEADERS.contains(&file_stem) {
                files.push(path);
            }
        }
    }
}

fn main() {
    let src_dir = std::env::var("MONGOAC_SRC_DIR")
        .expect("MONGOAC_SRC_DIR is required (the Rust source root directory)");
    let include_dir = std::env::var("MONGOAC_INCLUDE_DIR")
        .expect("MONGOAC_INCLUDE_DIR is required (the output directory for generated headers)");

    let src_path = Path::new(&src_dir);
    let include_path = Path::new(&include_dir);

    let mut files = Vec::new();
    find_modules(src_path, &mut files);

    // Generate crate headers in parallel using Rayon.
    files
        .par_iter()
        .for_each(|path| generate_crate_header(path, src_path, include_path));
}
