def escape(s: str) -> str:
    # Non-ASCII (UTF-8) bytes are emitted as 3-digit octal escapes, which are
    # self-terminating in C and cannot run into following characters.
    out = []
    for byte in s.encode('utf-8'):
        ch = chr(byte)
        if ch == '"':
            out.append('\\"')
        elif ch == '\\':
            out.append('\\\\')
        elif 32 <= byte < 127:
            out.append(ch)
        else:
            out.append(f'\\{byte:03o}')
    return ''.join(out)


def main() -> int:
    dat_path = sys.argv[1] if len(sys.argv) > 1 else 'public_suffix_list.dat'
    out_path = sys.argv[2] if len(sys.argv) > 2 else 'mongoc-psl-data.c'

    with open(dat_path, 'r', encoding='utf-8') as f:
        rules = [line.rstrip('\n') for line in f if line.strip()]

    chunks = []
    for rule in rules:
        chunks.append('"' + escape(rule) + '\\0"')

    with open(out_path, 'w', encoding='utf-8') as f:
        f.write(LICENSE)
        f.write('\n#include <stddef.h>\n\n')
        f.write('const char *const mongoc_psl_rules[] = {\n')
        for c in chunks:
            f.write(f'   {c},\n')
        f.write('};\n\n')
        f.write(f'const size_t mongoc_psl_rules_count = {len(chunks)};\n')

    print(f'wrote {out_path}: {len(chunks)} rules')
    return 0


if __name__ == '__main__':
    sys.exit(main())
