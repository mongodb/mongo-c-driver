// Generates src/libmongoc/src/mongoc/mongoc-psl-data.c from public_suffix_list.dat.
//
// The .dat file is vendored from the MongoDB specifications repository
// (source/public-suffix-list/public_suffix_list.dat); see CDRIVER-6542. Each
// rule is canonicalized here with mongoc_punycode_canonicalize_domain() (the
// same function applied to srvAllowedHostsSuffix at runtime), so the driver
// does no parsing, canonicalization, or heap allocation to load the list.
//
// This is a developer tool. It is not part of the default build. To regenerate
// the data after refreshing public_suffix_list.dat:
//
//    cmake -B cmake-build                                   # once
//    cmake --build cmake-build --target generate-psl-data
//    cmake-build/src/libmongoc/generate-psl-data \
//       src/public-suffix-list/public_suffix_list.dat \
//       src/libmongoc/src/mongoc/mongoc-psl-data.c
//
// The tool intentionally does not link the mongoc library: that library embeds
// the file this tool generates.

#include <mongoc/mongoc-punycode-private.h>

#include <mlib/str.h>

#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define MAX_LINE 1024u

typedef struct {
   uint32_t labels_offset;
   uint8_t nlabels;
   bool exception;
   char *text; // Canonical rule in domain order, for a comment in the output.
} rule_t;

typedef struct {
   char *data;
   size_t len;
   size_t cap;
} buffer_t;

static void
die(const char *msg, const char *detail)
{
   fprintf(stderr, "generate-psl-data: %s%s%s\n", msg, detail ? ": " : "", detail ? detail : "");
   exit(1);
}

static void *
checked_realloc(void *ptr, size_t size)
{
   void *const out = realloc(ptr, size);
   if (!out) {
      die("out of memory", NULL);
   }
   return out;
}

static void
buffer_append(buffer_t *buf, const char *bytes, size_t n)
{
   if (buf->len + n > buf->cap) {
      size_t cap = buf->cap ? buf->cap : 4096u;
      while (cap < buf->len + n) {
         cap *= 2u;
      }
      buf->data = checked_realloc(buf->data, cap);
      buf->cap = cap;
   }
   memcpy(buf->data + buf->len, bytes, n);
   buf->len += n;
}

// Append the labels of `canonical` (dot-separated) to `labels` right-to-left,
// each NUL-terminated. Returns the number of labels.
static size_t
append_reversed_labels(buffer_t *labels, const char *canonical)
{
   const size_t len = strlen(canonical);
   size_t nlabels = 0;
   size_t end = len; // One past the end of the label being scanned.

   for (size_t i = len + 1u; i > 0u; i--) {
      const size_t pos = i - 1u;
      if (pos == 0u || canonical[pos - 1u] == '.') {
         buffer_append(labels, canonical + pos, end - pos);
         buffer_append(labels, "", 1u); // NUL terminator.
         nlabels++;
         end = pos > 0u ? pos - 1u : 0u;
      }
   }
   return nlabels;
}

static void
write_output(const char *path, const buffer_t *labels, const rule_t *rules, size_t nrules)
{
   FILE *const out = fopen(path, "w");
   if (!out) {
      die("cannot open output file", path);
   }

   fputs("/*\n"
         " * Copyright 2009-present MongoDB, Inc.\n"
         " *\n"
         " * Licensed under the Apache License, Version 2.0 (the \"License\");\n"
         " * you may not use this file except in compliance with the License.\n"
         " * You may obtain a copy of the License at\n"
         " *\n"
         " *   http://www.apache.org/licenses/LICENSE-2.0\n"
         " *\n"
         " * Unless required by applicable law or agreed to in writing, software\n"
         " * distributed under the License is distributed on an \"AS IS\" BASIS,\n"
         " * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.\n"
         " * See the License for the specific language governing permissions and\n"
         " * limitations under the License.\n"
         " */\n\n"
         "// DO NOT EDIT !!!!\n"
         "// Generated by src/public-suffix-list/generate-psl-data.c from\n"
         "// src/public-suffix-list/public_suffix_list.dat\n"
         "//\n"
         "// mongoc_psl_label_data holds every rule's labels, already canonicalized\n"
         "// (ASCII-lowercase, Punycode) and ordered right-to-left, each NUL-terminated.\n"
         "// mongoc_psl_rules[i].labels_offset is where the i'th rule's labels start in\n"
         "// that block, and .nlabels is how many there are. The label block is a list\n"
         "// of byte values (not a quoted string), because it is too long for some\n"
         "// compilers' string literal length limits. Each rule's entry in\n"
         "// mongoc_psl_rules carries a comment naming the rule.\n\n"
         "#include <mongoc/mongoc-psl-private.h>\n\n"
         "#include <stddef.h>\n\n",
         out);

   fputs("// clang-format off\n\n", out);

   fprintf(out, "const char mongoc_psl_label_data[%zu] = {", labels->len);
   for (size_t i = 0; i < labels->len; i++) {
      fprintf(out, "%s%u,", (i % 32u == 0u) ? "\n   " : "", (unsigned)(unsigned char)labels->data[i]);
   }
   fputs("\n};\n\n", out);

   fprintf(out, "const mongoc_psl_rule_t mongoc_psl_rules[%zu] = {\n", nrules);
   for (size_t i = 0; i < nrules; i++) {
      fprintf(out,
              "   {%u, %u, %u}, // %s%s\n",
              (unsigned)rules[i].labels_offset,
              (unsigned)rules[i].nlabels,
              rules[i].exception ? 1u : 0u,
              rules[i].exception ? "!" : "",
              rules[i].text);
   }
   fputs("};\n\n", out);
   fprintf(out, "const size_t mongoc_psl_rules_count = %zu;\n", nrules);

   if (fclose(out) != 0) {
      die("error writing output file", path);
   }
}

int
main(int argc, char **argv)
{
   if (argc != 3) {
      fprintf(stderr, "usage: %s <public_suffix_list.dat> <mongoc-psl-data.c>\n", argv[0]);
      return 2;
   }

   FILE *const in = fopen(argv[1], "r");
   if (!in) {
      die("cannot open input file", argv[1]);
   }

   buffer_t labels = {0};
   rule_t *rules = NULL;
   size_t nrules = 0;
   size_t rules_cap = 0;

   char line[MAX_LINE];
   while (fgets(line, sizeof line, in)) {
      size_t len = strlen(line);
      if (len == sizeof line - 1u && line[len - 1u] != '\n') {
         die("line too long", line);
      }
      while (len > 0u && (line[len - 1u] == '\n' || line[len - 1u] == '\r')) {
         line[--len] = '\0';
      }
      // Blank lines and comments are not rules.
      if (len == 0u || (len >= 2u && line[0] == '/' && line[1] == '/')) {
         continue;
      }

      const char *rule = line;
      bool exception = false;
      if (*rule == '!') {
         exception = true;
         rule++;
      }

      mstr canonical = mstr_new(0);
      if (!mongoc_punycode_canonicalize_domain(rule, strlen(rule), &canonical)) {
         die("cannot canonicalize rule", line);
      }

      if (labels.len > UINT32_MAX) {
         die("label data too large", NULL);
      }
      const size_t offset = labels.len;
      const size_t nlabels = append_reversed_labels(&labels, canonical.data);

      if (nlabels == 0u || nlabels > 128u) {
         die("unsupported number of labels in rule", line);
      }

      if (nrules == rules_cap) {
         rules_cap = rules_cap ? rules_cap * 2u : 1024u;
         rules = checked_realloc(rules, rules_cap * sizeof *rules);
      }
      rules[nrules].labels_offset = (uint32_t)offset;
      rules[nrules].nlabels = (uint8_t)nlabels;
      rules[nrules].exception = exception;
      rules[nrules].text = checked_realloc(NULL, canonical.len + 1u);
      memcpy(rules[nrules].text, canonical.data, canonical.len + 1u);
      nrules++;

      mstr_destroy(&canonical);
   }
   fclose(in);

   write_output(argv[2], &labels, rules, nrules);
   printf("wrote %s: %zu rules, %zu bytes of label data\n", argv[2], nrules, labels.len);

   for (size_t i = 0; i < nrules; i++) {
      free(rules[i].text);
   }
   free(rules);
   free(labels.data);
   return 0;
}
