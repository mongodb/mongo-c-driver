#include <mongoc/mongoc-psl-private.h>
#include <mongoc/mongoc-punycode-private.h>

#include <mlib/str.h>

#include <TestSuite.h>

#include <stdio.h>
#include <string.h>

// The vendored list, relative to the repository root (like JSON_DIR).
#ifndef PSL_DAT_PATH
#define PSL_DAT_PATH "src/public-suffix-list/public_suffix_list.dat"
#endif

// Check that the embedded rules (mongoc-psl-data.c, generated by
// src/public-suffix-list/generate-psl-data.c) are what the driver itself would
// produce from the vendored list. Rules are compared against the output of
// mongoc_punycode_canonicalize_domain, the function applied to the user's
// srvAllowedHostsSuffix at runtime, so both sides are in the same form.
//
// This also fails if public_suffix_list.dat is updated without regenerating
// mongoc-psl-data.c.
static void
test_psl_data_matches_list(void)
{
   FILE *const in = fopen(PSL_DAT_PATH, "r");
   ASSERT_WITH_MSG(in, "could not open %s (run from the repository root)", PSL_DAT_PATH);

   char line[1024];
   size_t i = 0;
   while (fgets(line, sizeof line, in)) {
      size_t len = strlen(line);
      while (len > 0u && (line[len - 1u] == '\n' || line[len - 1u] == '\r')) {
         line[--len] = '\0';
      }
      if (len == 0u || (len >= 2u && line[0] == '/' && line[1] == '/')) {
         continue; // Blank lines and comments are not rules.
      }

      const bool exception = line[0] == '!';
      const char *const rule = line + (exception ? 1 : 0);

      mstr expected = mstr_new(0);
      ASSERT_WITH_MSG(mongoc_punycode_canonicalize_domain(rule, strlen(rule), &expected),
                      "rule \"%s\" cannot be canonicalized",
                      line);

      ASSERT_WITH_MSG(i < mongoc_psl_rules_count,
                      "mongoc-psl-data.c has only %zu rules, but %s has more (regenerate it)",
                      mongoc_psl_rules_count,
                      PSL_DAT_PATH);

      const mongoc_psl_rule_t *const stored = &mongoc_psl_rules[i];
      ASSERT_WITH_MSG((stored->exception != 0u) == exception, "rule %zu \"%s\": wrong exception flag", i, line);

      // Rebuild the stored rule in domain order (the data is right-to-left).
      const char *labels[UINT8_MAX];
      const char *label = mongoc_psl_label_data + stored->labels_offset;
      for (size_t j = 0; j < stored->nlabels; j++) {
         labels[j] = label;
         label += strlen(label) + 1u;
      }
      char actual[1024] = "";
      size_t actual_len = 0u;
      for (size_t j = stored->nlabels; j > 0u; j--) {
         const size_t label_len = strlen(labels[j - 1u]);
         ASSERT_WITH_MSG(actual_len + label_len + 2u <= sizeof actual, "rule %zu \"%s\" is too long", i, line);
         memcpy(actual + actual_len, labels[j - 1u], label_len);
         actual_len += label_len;
         if (j > 1u) {
            actual[actual_len++] = '.';
         }
         actual[actual_len] = '\0';
      }

      ASSERT_WITH_MSG(0 == strcmp(actual, expected.data),
                      "rule %zu \"%s\": stored \"%s\", expected \"%s\" (regenerate mongoc-psl-data.c)",
                      i,
                      line,
                      actual,
                      expected.data);

      mstr_destroy(&expected);
      i++;
   }
   fclose(in);

   ASSERT_WITH_MSG(i == mongoc_psl_rules_count,
                   "%s has %zu rules, but mongoc-psl-data.c has %zu (regenerate it)",
                   PSL_DAT_PATH,
                   i,
                   mongoc_psl_rules_count);
}

void
test_psl_install(TestSuite *suite)
{
   TestSuite_Add(suite, "/Psl/data_matches_list", test_psl_data_matches_list);
}
