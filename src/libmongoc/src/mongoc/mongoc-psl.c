// The vendored PSL rules, embedded as string literals (generated by
// src/public-suffix-list/generate-c-data.py; DO NOT EDIT).
extern const char *const mongoc_psl_rules[];
extern const size_t mongoc_psl_rules_count;

#define PSL_MAX_LABELS 128u

// A single parsed rule. Labels are stored right-to-left (the rule's rightmost
// label first) in canonical form (ASCII lowercase, Punycode), so matching a
// canonical domain reduces to a label-by-label comparison from the left of
// both reversed sequences. A wildcard rule's '*' (its original leftmost
// label) is therefore the LAST stored label and matches exactly one domain
// label.
typedef struct _mongoc_psl_rule {
   char **labels; // Owned array of `nlabels` owned strings; labels[i] is the i'th label from the right.
   size_t nlabels;
   bool exception; // Rule was prefixed '!'.
} mongoc_psl_rule_t;

struct _mongoc_psl {
   mongoc_psl_rule_t *rules;
   size_t nrules;
};

static void
_psl_rule_destroy(mongoc_psl_rule_t *rule)
{
   for (size_t i = 0; i < rule->nlabels; i++) {
      bson_free(rule->labels[i]);
   }
   bson_free(rule->labels);
   memset(rule, 0, sizeof(*rule));
}

// Parse one rule line (the vendored file format guarantees no comments or
// blank lines) into canonical labels stored right-to-left.
static bool
_psl_parse_rule(const char *rule, mongoc_psl_rule_t *out)
{
   memset(out, 0, sizeof(*out));

   const char *cursor = rule;
   if (*cursor == '!') {
      out->exception = true;
      cursor++;
   }

   // Canonicalize the whole rule at once (each dot-separated label is
   // ASCII-lowercased or Punycode-encoded), then store the labels
   // right-to-left. A '*' label flows through as a regular label and is
   // interpreted during matching.
   char *reversed[PSL_MAX_LABELS] = {0};
   size_t nlabels = 0;

   mstr canonical = mstr_new(0);
   if (!mongoc_punycode_canonicalize_domain(cursor, strlen(cursor), &canonical)) {
      mstr_destroy(&canonical);
      goto fail;
   }

   {
      // Split canonical into labels (left-to-right), inserting each at the
      // front of the reversed list.
      const char *label_start = canonical.data;
      for (const char *c = canonical.data;; c++) {
         if (*c == '.' || *c == '\0') {
            if (nlabels == PSL_MAX_LABELS) {
               mstr_destroy(&canonical);
               goto fail;
            }
            for (size_t i = nlabels; i > 0; i--) {
               reversed[i] = reversed[i - 1];
            }
            reversed[0] = bson_malloc0((size_t)(c - label_start) + 1);
            memcpy(reversed[0], label_start, (size_t)(c - label_start));
            nlabels++;

            if (*c == '\0') {
               break;
            }
            label_start = c + 1;
         }
      }
   }
   mstr_destroy(&canonical);

   // Size the stored array to exactly this rule's label count.
   out->labels = bson_malloc0(nlabels * sizeof(*out->labels));
   for (size_t i = 0; i < nlabels; i++) {
      out->labels[i] = reversed[i];
      reversed[i] = NULL;
   }
   out->nlabels = nlabels;
   return true;

fail:
   for (size_t i = 0; i < PSL_MAX_LABELS; i++) {
      bson_free(reversed[i]);
   }
   return false;
}

mongoc_psl_t *
mongoc_psl_new(bson_error_t *error)
{
   mongoc_psl_t *psl = bson_malloc0(sizeof(*psl));
   psl->rules = bson_malloc0(mongoc_psl_rules_count * sizeof(*psl->rules));
   psl->nrules = 0;

   for (size_t i = 0; i < mongoc_psl_rules_count; i++) {
      mongoc_psl_rule_t rule;
      if (!_psl_parse_rule(mongoc_psl_rules[i], &rule)) {
         bson_set_error(error,
                        MONGOC_ERROR_STREAM,
                        MONGOC_ERROR_STREAM_NAME_RESOLUTION,
                        "invalid public suffix list rule: %s",
                        mongoc_psl_rules[i]);
         mongoc_psl_destroy(psl);
         return NULL;
      }
      psl->rules[psl->nrules++] = rule;
   }

   return psl;
}

void
mongoc_psl_destroy(mongoc_psl_t *psl)
{
   if (!psl) {
      return;
   }
   for (size_t i = 0; i < psl->nrules; i++) {
      _psl_rule_destroy(&psl->rules[i]);
   }
   bson_free(psl->rules);
   bson_free(psl);
}

// Split a canonical domain into labels stored right-to-left (the domain's
// rightmost label first; label *contents* are not reversed). The label
// pointers alias `buf`, which the caller owns. Returns the number of labels,
// or 0 on overflow.
static size_t
_psl_split_reversed(const char *domain, const char *reversed[PSL_MAX_LABELS], char *buf, size_t buf_size)
{
   const size_t domain_len = strlen(domain);
   if (domain_len + 1 > buf_size) {
      return 0;
   }
   memcpy(buf, domain, domain_len + 1);

   size_t nlabels = 0;
   const char *start = buf;
   for (char *c = buf;; c++) {
      if (*c == '.' || *c == '\0') {
         if (nlabels == PSL_MAX_LABELS) {
            return 0;
         }
         if (c == start) {
            return 0; // Empty label.
         }
         reversed[nlabels++] = start;
         if (*c == '\0') {
            break;
         }
         *c = '\0';
         start = c + 1;
      }
   }

   // Reverse the label pointer array: rightmost domain label first.
   for (size_t i = 0; i < nlabels / 2; i++) {
      const char *tmp = reversed[i];
      reversed[i] = reversed[nlabels - 1 - i];
      reversed[nlabels - 1 - i] = tmp;
   }
   return nlabels;
}

static bool
_label_equal(const char *a, const char *b)
{
   return 0 == strcmp(a, b);
}

// Find the prevailing rule for `domain` per the PSL algorithm. Outputs the
// number of labels the public suffix occupies (for an exception rule, the
// rule's own label count minus its leftmost label), and whether the
// prevailing rule was an exception rule. Returns false when no rule matches
// (the implicit '*' rule: the rightmost label alone is the public suffix).
static bool
_psl_prevailing(const mongoc_psl_t *psl, const char *domain, size_t *out_labels, bool *out_exception)
{
   char rev[512] = {0};
   const char *labels[PSL_MAX_LABELS] = {0};
   const size_t ndomain_labels = _psl_split_reversed(domain, labels, rev, sizeof(rev));
   if (ndomain_labels == 0) {
      return false;
   }

   bool has_match = false;
   size_t best_labels = 0;
   bool best_is_exception = false;

   for (size_t i = 0; i < psl->nrules; i++) {
      const mongoc_psl_rule_t *const rule = &psl->rules[i];

      if (ndomain_labels < rule->nlabels) {
         continue; // The rule needs more labels than the domain has.
      }

      bool matches = true;
      for (size_t j = 0; j < rule->nlabels; j++) {
         if (j == rule->nlabels - 1u && 0 == strcmp(rule->labels[j], "*")) {
            continue; // '*' matches exactly one domain label.
         }
         if (!_label_equal(rule->labels[j], labels[j])) {
            matches = false;
            break;
         }
      }
      if (!matches) {
         continue;
      }

      // Exception rules always prevail; otherwise the most labels prevail.
      if (rule->exception) {
         best_labels = rule->nlabels - 1u;
         best_is_exception = true;
         has_match = true;
         break; // An exception rule always prevails; no need to keep looking.
      }
      if (!has_match || rule->nlabels > best_labels || best_is_exception) {
         best_labels = rule->nlabels;
         best_is_exception = false;
         has_match = true;
      }
   }

   if (!has_match) {
      return false;
   }
   *out_labels = best_labels;
   *out_exception = best_is_exception;
   return true;
}

bool
mongoc_psl_is_public_suffix(const mongoc_psl_t *psl, const char *domain)
{
   BSON_ASSERT_PARAM(psl);
   BSON_ASSERT_PARAM(domain);

   size_t ndomain_labels = 1;
   for (const char *c = domain; *c; c++) {
      if (*c == '.') {
         ndomain_labels++;
      }
   }

   size_t suffix_labels = 1;
   bool is_exception = false;
   if (_psl_prevailing(psl, domain, &suffix_labels, &is_exception)) {
      if (is_exception) {
         // An exception rule prevailing marks the domain as registrable
         // (explicitly NOT a public suffix).
         return false;
      }
      return ndomain_labels == suffix_labels;
   }

   // No rule matched: the implicit '*' rule declares the rightmost label
   // alone to be the public suffix.
   return ndomain_labels == 1;
}

static mongoc_psl_t *_psl_singleton = NULL;

static BSON_ONCE_FUN(_mongoc_psl_singleton_init)
{
   _psl_singleton = mongoc_psl_new(NULL);
   BSON_ONCE_RETURN;
}

mongoc_psl_t *
mongoc_psl_get_singleton(void)
{
   static bson_once_t once = BSON_ONCE_INIT;
   bson_once(&once, _mongoc_psl_singleton_init);
   return _psl_singleton;
}
